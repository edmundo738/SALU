export function formatKwanza(amount?: number, lang: 'pt' | 'en' = 'pt'): string {
  if (amount === undefined || amount === null) {
    return lang === 'pt' ? 'Negociável' : 'Negotiable';
  }
  return `${amount.toLocaleString('en-US')} Kz`;
}

